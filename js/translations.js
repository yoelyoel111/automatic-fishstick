let currentLanguage = 'he';

function setLanguage(lang) {
    currentLanguage = lang;
    const isRtl = lang === 'he';
    
    // Update HTML attributes
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (el.tagName === 'TITLE') {
                document.title = translations[lang][key];
            } else if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                el.placeholder = translations[lang][key];
            } else {
                el.innerText = translations[lang][key];
            }
        }
    });

    // Update all elements with data-i18n-title attribute
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (translations[lang][key]) {
            el.title = translations[lang][key];
        }
    });

    // Update all elements with data-i18n-alt attribute
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
        const key = el.getAttribute('data-i18n-alt');
        if (translations[lang][key]) {
            el.alt = translations[lang][key];
        }
    });

    // Handle special cases (HTML content)
    const instructions = document.getElementById('namesUploadInstructions');
    if (instructions) {
        instructions.innerHTML = translations[lang]['simpleInstructions'];
    }

    // Update toggle button
    const toggleBtn = document.getElementById('languageToggleBtn');
    if (toggleBtn) {
        toggleBtn.innerText = translations[lang]['langToggle'] === 'English' ? '🌐 English' : '🌐 עברית';
    }

    // Save preference
    localStorage.setItem('preferredLanguage', lang);
    
    // Trigger any language-specific UI updates
    if (typeof applyPrintPreviewScale === 'function') {
        applyPrintPreviewScale();
    }
}

function t(key, params = {}) {
    let text = translations[currentLanguage][key] || key;
    for (const [pKey, pVal] of Object.entries(params)) {
        text = text.replace(`{${pKey}}`, pVal);
    }
    return text;
}

// Initialize language on load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('preferredLanguage') || 'he';
    setLanguage(savedLang);
    
    const toggleBtn = document.getElementById('languageToggleBtn');
    if (toggleBtn) {
        toggleBtn.addEventListener('click', () => {
            const nextLang = currentLanguage === 'he' ? 'en' : 'he';
            setLanguage(nextLang);
        });
    }
});
